"""Generate HPACK tables (RFC 7541 Appendix A and B) as Tarn source from
golang.org/x/net/http2/hpack/tables.go, an independent implementation.
Usage: python3 -I gen_hpack_tables.py path/to/hpack > hpack_tables.tarn"""
import pathlib
import re
import sys

source = (pathlib.Path(sys.argv[1]) / 'tables.go').read_text()

def array(name):
    body = re.search(r'var %s = \[256\]uint\d+\{(.*?)\n\}' % name, source, re.S).group(1)
    return [int(v, 0) for v in re.findall(r'0x[0-9a-f]+|\b\d+\b', body)]

codes, lengths = array('huffmanCodes'), array('huffmanCodeLen')
assert len(codes) == len(lengths) == 256
symbols = sorted(range(256), key=lambda s: (lengths[s], codes[s]))
first, count, offset = [0] * 31, [0] * 31, [0] * 31
position = 0
for length in range(1, 31):
    members = [s for s in symbols if lengths[s] == length]
    offset[length] = position
    count[length] = len(members)
    if members:
        first[length] = codes[members[0]]
        # Canonical code: each length's codes are consecutive.
        assert [codes[s] for s in members] == list(range(first[length], first[length] + len(members))), length
    position += len(members)
# EOS (30 bits, all ones) is not a symbol and must never decode.
assert first[30] + count[30] == 0x3fffffff

static = re.search(r'ents: \[\]HeaderField\{(.*?)\n\t\}', (pathlib.Path(sys.argv[1]) / 'static_table.go').read_text(), re.S).group(1)
entries = re.findall(r'\{Name: "([^"]*)", Value: "([^"]*)"', static)
assert len(entries) == 61, len(entries)

def tarn_array(kind, values):
    return '[%d]%s{%s}' % (len(values), kind, ', '.join(str(v) for v in values))

print('// Generated by tools/gen_hpack_tables.py from golang.org/x/net/http2/hpack.')
print('// Canonical Huffman decoding tables, RFC 7541 Appendix B. Do not edit.')
print('pub fn huffman_symbols() [256]u8 { return %s }' % tarn_array('u8', symbols))
print('pub fn huffman_first() [31]u32 { return %s }' % tarn_array('u32', first))
print('pub fn huffman_count() [31]u32 { return %s }' % tarn_array('u32', count))
print('pub fn huffman_offset() [31]u32 { return %s }' % tarn_array('u32', offset))
print('// Static table, RFC 7541 Appendix A; index 1 is entry 0.')
print('pub fn static_name(index usize) string {')
for i, (name, _) in enumerate(entries):
    print('    if index == %d { return "%s" }' % (i + 1, name))
print('    return ""\n}')
print('pub fn static_value(index usize) string {')
for i, (_, value) in enumerate(entries):
    if value:
        print('    if index == %d { return "%s" }' % (i + 1, value))
print('    return ""\n}')
